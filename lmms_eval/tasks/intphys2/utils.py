"""IntPhys 2 · 物体恒常性 / 运动连续性（lmms-eval task，挂 #35 / #38）。

    intphys2_permanence   240 个视频（120 可能 / 120 不可能）  #35 物体恒常性
    intphys2_continuity   240 个视频（120 可能 / 120 不可能）  #38 运动连续性

数据：facebook/IntPhys2 Main 集（CC BY-NC 4.0，仅限评测用途）。每个视频一题：模型看帧序列，判断
物体行为是否符合物理规律。帧由 build_intphys2_frames.py 按官方做法抽取（1 帧/秒，每视频 11 张）。

协议（照官方 facebookresearch/IntPhys2 的 IntPhys2_openai.py / ComputeScoreIntPhys2.ipynb）
-----------------------------------------------------------------------------------
* 提示词 = 官方 prompt1（「Finish your answer by Yes or No」），一字不改。
* 判分 = 官方 label_pred_yes_no：回复里出现 yes/Yes → 判「可能」，否则出现 no/No → 「不可能」，
  都没有 → 无效（计错）。⚠️ 官方是**子串**匹配且 yes 优先（「not」「know」里的 no 也会命中），
  这里为了与官方数字可比照搬，另外出一个 intphys2_accuracy_strict 指标：只看去掉 <think> 后
  **最后一个**整词 yes/no，作为稳健性对照。
* 主指标 = 单视频准确率；分母是全部视频（无效回复计错，与官方 calculate_accuracy 一致）。

⚠️ 读分须知
-----------
* 可能/不可能各一半，**全答 Yes 就是 50%**。论文里 GPT-4o / Gemini 2.5 Flash 在 permanence
  55–64、continuity 53–57，人类 >90。所以另出 intphys2_yes_rate（答「可能」的比例）：
  接近 100% 说明模型在一律放行，准确率再接近 50 也不代表有判断力。
* intphys2_pair_accuracy：同一场景 4 个视频（2 可能 + 2 不可能）里，可能视频判对且不可能视频
  也判对的「成对」比例 —— 一律答 Yes 的模型这项是 0。不是官方 MLLM 指标，仅作参考。
* 官方报告的是「多次运行 / 多个提示词里的最好成绩」，这里只跑一次 temperature=0，数字会偏低。
"""

from __future__ import annotations

import pathlib
import re
from collections import defaultdict
from typing import Any, Dict, List

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
MEDIA = HERE / "media"

# 官方 prompt1（IntPhys2_openai.py / IntPhys2_google_api.py），原样照抄，含弯引号
PROMPT = (
    "The video you’re seeing was generated by a simulator. Given how objects behave on earth, "
    "is the behaviour of the objects plausible? Your answer should be based on the events in the "
    "video and ignore the quality of the simulation. You should also ignore the framerate of the "
    "video, as it may be slowed down. Finish your answer by Yes or No"
)


def intphys2_doc_to_visual(doc: Dict[str, Any]) -> List[Image.Image]:
    out = []
    for rel in doc["frames"]:
        with Image.open(MEDIA / rel) as im:
            out.append(im.convert("RGB"))
    return out


def intphys2_doc_to_text(doc: Dict[str, Any], lmms_eval_specific_kwargs: Dict[str, Any] | None = None) -> str:
    return PROMPT


def intphys2_doc_to_target(doc: Dict[str, Any]) -> str:
    return "Yes" if doc["label"] == "Possible" else "No"


def _strip_think(text: str) -> str:
    for tag in ("</think>", "</thought>"):
        if tag in text:
            text = text.rsplit(tag, 1)[1]
    return text.strip()


def official_label(text: str) -> int:
    """官方 label_pred_yes_no：1=可能，0=不可能，2=无效。子串匹配、yes 优先。"""
    if "yes" in text or "Yes" in text:
        return 1
    if "no" in text or "No" in text:
        return 0
    return 2


def strict_label(text: str) -> int:
    """最后一个整词 yes/no（不分大小写）；没有则无效。"""
    hits = re.findall(r"\b(yes|no)\b", text, flags=re.IGNORECASE)
    if not hits:
        return 2
    return 1 if hits[-1].lower() == "yes" else 0


def intphys2_process_results(doc: Dict[str, Any], results: List[str]) -> Dict[str, Any]:
    raw = results[0] if results else ""
    failed = (not raw) or raw.startswith("[LMMS_EVAL_REQUEST_FAILED")
    body = "" if failed else _strip_think(raw)
    target = 1 if doc["label"] == "Possible" else 0
    pred = official_label(body)
    pred_s = strict_label(body)
    entry = {
        "id": doc["id"],
        "scene": doc["scene"],
        "label": doc["label"],
        "difficulty": doc["difficulty"],
        "camera": doc["camera"],
        "pred": pred,
        "pred_strict": pred_s,
        "is_correct": pred == target,
        "is_correct_strict": pred_s == target,
        "response": body[-500:],
    }
    return {k: entry for k in (
        "intphys2_accuracy", "intphys2_accuracy_strict", "intphys2_yes_rate",
        "intphys2_valid_rate", "intphys2_pair_accuracy",
    )}


def _mean(xs):
    xs = list(xs)
    return sum(xs) / len(xs) if xs else 0.0


def intphys2_aggregate_accuracy(results):
    return _mean(r["is_correct"] for r in results)


def intphys2_aggregate_accuracy_strict(results):
    return _mean(r["is_correct_strict"] for r in results)


def intphys2_aggregate_yes_rate(results):
    valid = [r for r in results if r["pred"] != 2]
    return _mean(r["pred"] == 1 for r in valid)


def intphys2_aggregate_valid_rate(results):
    return _mean(r["pred"] != 2 for r in results)


def intphys2_aggregate_pair_accuracy(results):
    """每个场景：全部 4 个视频都判对才算 1。"""
    by_scene = defaultdict(list)
    for r in results:
        by_scene[r["scene"]].append(r["is_correct"])
    return _mean(all(v) for v in by_scene.values())
