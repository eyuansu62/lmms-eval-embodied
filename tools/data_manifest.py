#!/usr/bin/env python3
"""Record and restore the exact evaluation subsets used by the custom embodied tasks.

The repository does not redistribute benchmark data. Each task's builder script downloads the
original data and regenerates a superset of rows; ``MANIFEST.json`` lists the SHA-256 of every
line of every evaluated file (in order), so the exact files can be selected and verified.

    python tools/data_manifest.py record  <task_dir> [...]   # maintainers: write data/MANIFEST.json
    python tools/data_manifest.py restore <task_dir> [...]   # select rows by hash, verify file hashes
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

MANIFEST = "MANIFEST.json"


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def _lh(line: bytes) -> str:
    return _sha(line)[:16]


def _lines(p: pathlib.Path) -> list[bytes]:
    return [l if l.endswith(b"\n") else l + b"\n" for l in p.read_bytes().splitlines(keepends=True)]


def record(task_dir: pathlib.Path, files: list[pathlib.Path]) -> None:
    data = task_dir / "data"
    entries = {}
    for p in sorted(files):
        rel = str(p.relative_to(data))
        e = {"sha256": _sha(p.read_bytes())}
        if p.suffix == ".jsonl":
            e["lines"] = [_lh(l) for l in _lines(p)]
        entries[rel] = e
    (data / MANIFEST).write_text(json.dumps(entries, indent=1) + "\n", encoding="utf-8")
    print(f"{task_dir.name}: recorded {len(entries)} files")


def restore(task_dir: pathlib.Path) -> bool:
    data = task_dir / "data"
    entries = json.loads((data / MANIFEST).read_text(encoding="utf-8"))
    pool: dict[str, bytes] = {}
    for p in data.rglob("*.jsonl"):
        for l in _lines(p):
            pool.setdefault(_lh(l), l)
    ok = True
    for rel, e in entries.items():
        out = data / rel
        if out.is_file() and _sha(out.read_bytes()) == e["sha256"]:
            continue
        if "lines" not in e:
            print(f"  missing {task_dir.name}/data/{rel} (not regenerated by the builder)")
            ok = False
            continue
        missing = [h for h in e["lines"] if h not in pool]
        if missing:
            print(f"  {task_dir.name}/data/{rel}: {len(missing)}/{len(e['lines'])} rows not produced by the builder")
            ok = False
            continue
        body = b"".join(pool[h] for h in e["lines"])
        if _sha(body) != e["sha256"]:
            body = body[:-1] if body.endswith(b"\n") else body
        if _sha(body) != e["sha256"]:
            print(f"  {task_dir.name}/data/{rel}: rows match but file hash differs")
            ok = False
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(body)
    print(f"{task_dir.name}: {'OK' if ok else 'FAILED'} ({len(entries)} files)")
    return ok


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["record", "restore"])
    ap.add_argument("tasks", nargs="+", type=pathlib.Path)
    a = ap.parse_args()
    if a.cmd == "record":
        for t in a.tasks:
            files = [p for p in (t / "data").rglob("*") if p.is_file() and p.name != MANIFEST]
            record(t, files)
    else:
        sys.exit(0 if all(restore(t) for t in a.tasks) else 1)


if __name__ == "__main__":
    main()
